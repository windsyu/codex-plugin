const { readRun, runApiPath } = require('./workbench-api.cjs');
const { openCalls } = require('./call-inspector.cjs');
// Synthetic capture only: HTTP reverse results and multiplexed WS contexts.
const { expect } = require('playwright/test');
const { chromium, close } = require('./browser-lifecycle.cjs');
const assert = require('node:assert/strict');
let browser, page, stage = 'launch';
const report = value => process.stdout.write(`${JSON.stringify(value)}\n`);

const screenshot = async suffix => { if (page && process.env.WORKBENCH_PROBE_SCREENSHOT) await page.screenshot({ path: `${process.env.WORKBENCH_PROBE_SCREENSHOT}.${suffix}.png`, fullPage: true }); };
const snapshot = () => readRun(page, '/live/snapshot');
const run = () => readRun(page, '/run');
setTimeout(() => { report({ stage: 'failed', check: stage, reason: 'deadline' }); close(1); }, 55000).unref();

(async () => {
  browser = await chromium.launch({ executablePath: process.env.WORKBENCH_TEST_CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  page = await browser.newPage({ viewport: { width: 1600, height: 1000 } }); page.setDefaultTimeout(10000);
  let errors = 0, detailReads = 0;
  page.on('pageerror', () => errors++);
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith(runApiPath(process.env.WORKBENCH_PROBE_URL, '/requests/'))) detailReads++; });
  await page.goto(process.env.WORKBENCH_PROBE_URL);
  const terminal = page.locator('.xterm-helper-textarea');
  await expect(page.locator('.wb-terminal')).toHaveAttribute('data-owned', 'true');
  const terminalNode = await terminal.elementHandle(), beforeRun = await run();
  const messages = page.locator('.wb-message-list');
  const first = messages.locator('[data-call-id="http-first"]');
  const second = messages.locator('[data-call-id="http-second"]');
  report({ stage: 'ready' }); stage = 'http-partial';
  await expect(messages.locator('.wb-tool-card')).toHaveCount(2);
  await expect(first).toContainText('R2_HTTP_FIRST_PARTIAL');
  await expect(second).toContainText('R2_HTTP_SECOND_PARTIAL');
  await expect(messages.locator('[data-role="user"]')).toHaveCount(0);
  for (const card of [first, second]) {
    await expect(card).toContainText('参数生成中');
    await expect(card).toHaveAttribute('data-execution', 'unobserved');
    await card.locator('.wb-tool-arguments summary').press('Enter');
  }
  const firstNode = await first.elementHandle(), secondNode = await second.elementHandle();
  const initial = await snapshot();
  await messages.evaluate(element => { element.scrollTop = 180; element.dispatchEvent(new Event('scroll')); });
  await expect(page.locator('.wb-follow')).toBeVisible();
  const anchorTop = await messages.locator('[data-reading-key]').first().evaluate(element => element.getBoundingClientRect().top);
  const scrollTop = await messages.evaluate(element => element.scrollTop);
  await terminal.focus();
  report({ stage: 'http-partial' }); stage = 'http-results';
  await expect(messages.locator('.wb-model-message')).toHaveCount(2);
  await expect(messages).toContainText('R2_HTTP_FOLLOWING_REPLY');
  for (const [card, wanted, forbidden] of [[first, 'R2_FIRST_RESULT', 'R2_SECOND_RESULT'], [second, 'R2_SECOND_RESULT', 'R2_FIRST_RESULT']]) {
    await expect(card).toHaveAttribute('data-execution', 'result_observed');
    await expect(card.locator('.wb-tool-result')).toContainText(wanted);
    await expect(card.locator('.wb-tool-result')).not.toContainText(forbidden);
    await expect(card.locator('.wb-tool-arguments')).toHaveAttribute('open', '');
  }
  assert.equal(await firstNode.evaluate(element => element.isConnected), true);
  assert.equal(await secondNode.evaluate(element => element.isConnected), true);
  await expect(terminal).toBeFocused();
  await expect.poll(() => messages.evaluate(element => element.scrollTop)).toBe(scrollTop);
  const afterTop = await messages.locator('[data-reading-key]').first().evaluate(element => element.getBoundingClientRect().top);
  assert.ok(Math.abs(afterTop - anchorTop) < 2);
  const afterHttp = await snapshot();
  assert.deepEqual(afterHttp.items.slice(0, initial.items.length).map(item => item.itemKey), initial.items.map(item => item.itemKey));
  assert.deepEqual(await messages.locator('[data-reading-key] > article').evaluateAll(elements => elements.map(element => element.dataset.kind || element.dataset.role)), ['assistant', 'tool_call', 'tool_call', 'assistant']);
  await first.locator('.wb-tool-result summary').press('Enter');
  await expect(first.locator('.wb-tool-result pre')).toContainText('[已脱敏]');
  await expect(first.locator('img,script')).toHaveCount(0);
  assert.equal(detailReads, 0);
  await screenshot('http');
  report({ stage: 'http-reviewed' }); stage = 'ws-partial';
  await expect.poll(async () => (await snapshot()).requests.length).toBe(4);
  await expect(messages.locator('.wb-tool-card')).toHaveCount(2);
  await expect(messages.locator('.wb-model-message')).toHaveCount(2);
  await expect(messages.locator('[data-role="user"]')).toHaveCount(0);
  await openCalls(page);
  await page.locator('.wb-call-row').filter({ hasText: 'WebSocket' }).click();
  await page.locator('.wb-call-unassigned > summary').click();
  const request = page.locator('.wb-call-inspector');
  await expect(request).toHaveAttribute('data-purpose', 'unknown');
  await expect(request).toContainText('WebSocket create 2，响应关联未确认');
  const cards = request.locator('.wb-tool-card');
  await expect(cards).toHaveCount(2);
  const beta = cards.nth(0), alpha = cards.nth(1);
  await expect(alpha).toContainText('R2_WS_ALPHA_PARTIAL');
  await expect(beta).toContainText('R2_WS_BETA_PARTIAL');
  const alphaNode = await alpha.elementHandle(), betaNode = await beta.elementHandle();
  const wsBefore = await snapshot();
  const context = request.locator('.wb-request-context');
  await expect(context.locator('.wb-context-entry')).toHaveCount(4);
  const one = context.locator('.wb-context-entry').filter({ has: page.locator('summary', { hasText: '请求参数 · WebSocket create 1' }) });
  const two = context.locator('.wb-context-entry').filter({ has: page.locator('summary', { hasText: '请求参数 · WebSocket create 2' }) });
  await one.locator('summary').press('Enter');
  await expect(one.locator('pre')).toContainText('previous-fixture-response');
  await expect(two.locator('pre')).toContainText('another-previous-response');
  const contextNode = await one.elementHandle();
  await alpha.locator('.wb-tool-arguments summary').press('Enter');
  assert.equal(detailReads, 1);
  report({ stage: 'ws-partial' }); stage = 'ws-half';
  await expect(alpha).toContainText('R2_WS_ALPHA_FINAL');
  await expect(alpha).toContainText('参数已生成');
  await expect(beta).toContainText('参数生成中');
  await expect(alpha).toHaveAttribute('data-execution', 'unobserved');
  await expect(beta).toHaveAttribute('data-execution', 'unobserved');
  await expect(context.getByRole('region', { name: '响应用量 ws-alpha', exact: true })).toContainText('26');
  await expect(context.getByRole('region', { name: '响应用量 ws-beta', exact: true })).toContainText('尚未收到此响应的用量');
  await expect(request).toContainText('WebSocket create 3，响应关联未确认');
  await expect(alpha.locator('.wb-tool-arguments summary')).toBeFocused();
  assert.equal(detailReads, 1);
  assert.equal(await contextNode.evaluate(element => element.isConnected), true);
  await expect(one).toHaveAttribute('open', '');
  report({ stage: 'ws-half' }); stage = 'ws-complete';
  await expect(beta).toContainText('R2_WS_BETA_FINAL');
  await expect(beta).toContainText('参数已生成');
  await expect(cards).toHaveCount(2);
  await expect(request.locator('.wb-tool-result')).toHaveCount(0);
  assert.equal(await alphaNode.evaluate(element => element.isConnected), true);
  assert.equal(await betaNode.evaluate(element => element.isConnected), true);
  await expect(alpha.locator('.wb-tool-arguments')).toHaveAttribute('open', '');
  const alphaUsage = context.getByRole('region', { name: '响应用量 ws-alpha', exact: true });
  const betaUsage = context.getByRole('region', { name: '响应用量 ws-beta', exact: true });
  assert.deepEqual(await alphaUsage.locator('dd').allTextContents(), ['21', '未提供', '5', '未提供', '26', '未提供']);
  await expect(betaUsage.locator('dd')).toHaveText(['34', '未提供', '8', '未提供', '42', '未提供']);
  await expect(context.getByRole('region', { name: '响应用量 身份未确认', exact: true })).toContainText('尚未收到此响应的用量');
  await context.getByRole('button', { name: '刷新上下文' }).click();
  await expect(context.getByRole('button', { name: '刷新上下文' })).toBeEnabled();
  for (let n = 0; n < 4 && await context.getByRole('button', { name: '加载后续内容' }).count(); n++) {
    await context.getByRole('button', { name: '加载后续内容' }).click();
    await expect(context.getByRole('button', { name: '刷新上下文' })).toBeEnabled();
  }
  const three = context.locator('.wb-context-entry').filter({ has: page.locator('summary', { hasText: '请求参数 · WebSocket create 3' }) });
  await three.locator('summary').press('Enter');
  await expect(three.locator('pre')).toContainText('"previous_response_id": "ws-alpha"');
  await expect(context).toContainText('R2_WS_UNASSIGNED_RESULT');
  await expect(context).toContainText('响应关联未确认');
  for (const forbidden of ['fixture-sensitive-value', 'PRIVATE_WS_BASE64', 'PRIVATE_WS_REASONING', 'R2_UNSCOPED_MUST_NOT_APPEAR']) {
    assert.ok(!(await page.locator('body').textContent()).includes(forbidden));
  }
  assert.equal(await page.evaluate(() => Boolean(window.concurrentInjected)), false);
  assert.equal(await terminalNode.evaluate(element => element === document.querySelector('.xterm-helper-textarea')), true);
  const complete = await snapshot();
  assert.deepEqual(complete.items.map(item => item.itemKey), wsBefore.items.map(item => item.itemKey));
  await expect(request.locator('.wb-model-message')).toHaveCount(2);
  await expect(request.locator('.wb-model-message').nth(0)).toContainText('R2_WS_ALPHA_MODEL_FINAL');
  await expect(request.locator('.wb-model-message').nth(1)).toContainText('R2_WS_BETA_MODEL_FINAL');
  await screenshot('ws');
  for (const width of [1024, 736, 320]) {
    await page.setViewportSize({ width, height: 900 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  await screenshot('narrow');
  stage = 'reload';
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.reload();
  await expect(page.locator('.wb-terminal')).toHaveAttribute('data-owned', 'true');
  await expect(messages.locator('.wb-tool-card')).toHaveCount(2);
  await expect(messages.locator('.wb-model-message')).toHaveCount(2);
  await expect(messages.locator('[data-role="user"]')).toHaveCount(0);
  assert.deepEqual((await snapshot()).items.map(item => item.itemKey), complete.items.map(item => item.itemKey));
  const afterRun = await run();
  assert.equal(afterRun.runEpoch, beforeRun.runEpoch); assert.equal(afterRun.processId, beforeRun.processId);
  await openCalls(page);
  await page.locator('.wb-call-row').filter({ hasText: 'WebSocket' }).click();
  await page.locator('.wb-call-unassigned > summary').click();
  await expect(cards).toHaveCount(2);
  await expect(alpha).toHaveAttribute('data-execution', 'unobserved');
  await expect(beta).toHaveAttribute('data-execution', 'unobserved');
  assert.equal(errors, 0);
  report({ stage: 'complete', reverseAndDuplicateResults: true, stableCardsAndReadingAnchor: true, wsCreatesUnassigned: 3, independentWsResponses: 2, perResponseUsage: true, samePtyProcess: true, userMessages: 0, pageErrors: errors, browser: browser.version() });
  await close(0);
})().catch(async () => { await screenshot('failed').catch(() => {}); report({ stage: 'failed', check: stage, reason: 'assertion (private URL/output suppressed)' }); close(1); });
